-- ---------------------------------------------------------------------
-- Tabla general de mascotas (perros y gatos)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS tb_pet (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(20) NOT NULL,
    name          VARCHAR(50) NOT NULL,
    born_year     INTEGER      NOT NULL DEFAULT 0,
    color         VARCHAR(20) NOT NULL DEFAULT '',
    health_status VARCHAR(30) NOT NULL DEFAULT 'Healthy'
);

-- ---------------------------------------------------------------------
-- Tabla específica de perros
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS tb_dog (
    id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    breed    VARCHAR(30) NOT NULL DEFAULT '',
    pedigree BOOLEAN     NOT NULL DEFAULT FALSE,
    id_pet   INTEGER     NOT NULL REFERENCES tb_pet (id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- Tabla específica de gatos
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS tb_cat (
    id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    breed  VARCHAR(30) NOT NULL DEFAULT '',
    id_pet INTEGER     NOT NULL REFERENCES tb_pet (id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- Tablas del módulo veterinario (clases clsDoctor / clsVeterinary)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS tb_doctor (
    id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(150) NOT NULL,
    phone   VARCHAR(20),
    address VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS tb_hospital (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(50) NOT NULL,
    phone       VARCHAR(50),
    address     VARCHAR(50),
    patien_type INTEGER,
    id_doctor   INTEGER REFERENCES tb_doctor (id)
);

CREATE TABLE IF NOT EXISTS tb_pet_hospital (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pet      INTEGER NOT NULL REFERENCES tb_pet (id),
    id_hospital INTEGER NOT NULL REFERENCES tb_hospital (id)
);

-- ---------------------------------------------------------------------
-- Índices
-- ---------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_tb_pet_code    ON tb_pet (code);
CREATE INDEX IF NOT EXISTS idx_tb_dog_id_pet ON tb_dog (id_pet);
CREATE INDEX IF NOT EXISTS idx_tb_cat_id_pet ON tb_cat (id_pet);

